CREATE OR REPLACE FUNCTION public.socios_publicos_por_categoria()
RETURNS TABLE(nome text, modalidade text, categoria text)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT s.nome, s.modalidade, s.categoria
  FROM public.socios s
  WHERE s.ativo = true
    AND s.nome IS NOT NULL
    AND trim(s.nome) <> ''
    AND s.categoria IS NOT NULL
    AND trim(s.categoria) <> ''
    AND lower(coalesce(s.modalidade,'')) IN ('futebol','futsal')
  ORDER BY lower(s.modalidade), lower(s.categoria), lower(s.nome);
$$;
REVOKE ALL ON FUNCTION public.socios_publicos_por_categoria() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.socios_publicos_por_categoria() TO anon, authenticated;

